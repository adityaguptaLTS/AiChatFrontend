/**
 * Translation helper function.
 * Looks up translation by key and language code, falling back to English, then the key itself.
 */
export function t(key, lang = 'en') {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en?.[key] ?? key;
}
