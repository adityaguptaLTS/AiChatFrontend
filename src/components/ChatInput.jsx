import { useState, useRef, useEffect } from 'react';
import { ArrowUp, Square } from 'lucide-react';

export default function ChatInput({
  onSendMessage,
  onStopGeneration,
  isLoading = false,
  placeholder = 'Ask anything or paste code...',
}) {
  const [input, setInput] = useState('');
  const textareaRef = useRef(null);

  // Auto-resize textarea based on text height
  useEffect(() => {
    const el = textareaRef.current;
    if (!el) return;
    el.style.height = 'auto';
    const maxHeight = 200;
    const nextHeight = Math.min(el.scrollHeight, maxHeight);
    el.style.height = `${nextHeight}px`;
    // Toggle scrollbar only when exceeding maxHeight
    el.style.overflowY = el.scrollHeight > maxHeight ? 'auto' : 'hidden';
  }, [input]);

  // Focus textarea when component mounts or loading finishes
  useEffect(() => {
    if (!isLoading && textareaRef.current) {
      textareaRef.current.focus();
    }
  }, [isLoading]);

  const handleSubmit = (e) => {
    if (e) e.preventDefault();
    if (!input.trim() || isLoading) return;
    onSendMessage(input);
    setInput('');
    if (textareaRef.current) {
      textareaRef.current.style.height = 'auto';
    }
  };

  const handleKeyDown = (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      handleSubmit();
    }
  };

  const isSendDisabled = !input.trim() || isLoading;

  return (
    <div className="composer-container">
      <form onSubmit={handleSubmit} className="composer-box" role="region" aria-label="Message composer">
        <textarea
          ref={textareaRef}
          value={input}
          onChange={(e) => setInput(e.target.value)}
          onKeyDown={handleKeyDown}
          placeholder={placeholder}
          rows={1}
          disabled={isLoading}
          className="composer-textarea"
          aria-label="Prompt message input"
        />

        <div className="composer-controls">
          {isLoading ? (
            <button
              type="button"
              className="composer-btn stop-btn"
              onClick={onStopGeneration}
              aria-label="Stop generation"
              title="Stop generating response"
            >
              <Square size={16} fill="currentColor" />
            </button>
          ) : (
            <button
              type="submit"
              disabled={isSendDisabled}
              className={`composer-btn send-btn ${isSendDisabled ? 'disabled' : 'active'}`}
              aria-label="Send message"
              title="Send message (Enter)"
            >
              <ArrowUp size={18} strokeWidth={2.5} />
            </button>
          )}
        </div>
      </form>

      <p className="composer-disclaimer">
        Responses are generated by the connected local AI engine.
      </p>
    </div>
  );
}
